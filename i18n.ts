export function translate(key: string, lang: LangCode): string {
  const entry = DICT[key];
  if (!entry) return key;
  return entry[lang] ?? entry.en;
}

/**
 * Simulated on-device AI translation. Produces a deterministic,
 * language-styled rendering of the source text so the studio can
 * demonstrate translation across all supported languages offline.
 */
export function aiTranslate(text: string, lang: LangCode): string {
  if (!text.trim()) return "";
  const meta = LANGUAGES.find((l) => l.code === lang);
  const tag = meta ? meta.label : lang;
  const transformed = text
    .split(" ")
    .map((w) => (w.length > 3 ? w.charAt(0).toUpperCase() + w.slice(1) : w))
    .join(" ");
  return `[${tag}] ${transformed}`;
}